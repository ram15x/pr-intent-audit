"""Regenerate the gold review sheets from the CURRENT label files (the old REVIEW.md went stale after label fixes).
bench/gold/REVIEW.md        committed: requirement text, label, confidence, note, hunk ids. No code.
bench/gold/REVIEW_LOCAL.md  gitignored: the same plus short excerpts of the cited diff lines, for your own review.
Fill the `your_label` column (done|partial|missing|unclear|exclude) in the LOCAL file. Usage: python bench/make_review_sheet.py"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from pr_audit.schemas import PRBundle

B = {}
for f in ("bundles.jsonl", "gold_pool.jsonl", "large_pool.jsonl"):
    for l in open(ROOT / "bench/data" / f, encoding="utf-8"):
        b = PRBundle.model_validate_json(l); B[b.source] = b
SETS = [("gold_draft.json", "Main gold set (14 PRs: the headline numbers rest on these)"),
        ("gold_extra_draft.json", "Extra gold set (6 PRs)"), ("gold_large_draft.json", "Large-PR gold set (16 PRs; used for retrieval numbers)")]
RULE = """## Rule to decide first (proposed, not yet adopted)
The tool can only see the diff, so label by what the diff shows:
- **done**: the changed lines, or the unchanged context printed with them, show the behaviour or file the requirement names.
- **partial**: some of it is shown, part is not.
- **missing**: the requirement is about something this diff should have contained and does not.
- **unclear**: it depends on code or behaviour outside the diff, on the *absence* of a change ("changes no prompt"), or on reuse of existing code that the diff only calls.
- **exclude**: not a requirement on the code (template line, issue number, background).
The current labels mix this rule with "the behaviour is true after the PR". Under the strict rule some `done` labels become `unclear`, which lowers the base rate and changes every precision figure. Re-scoring after relabelling needs no new LLM calls (judge answers are cached).
"""
pub, loc = ["# Gold labels: review sheet (generated by bench/make_review_sheet.py)", "",
            "All labels are Claude drafts; `reviewed_by_human` is false in every file until you change it. Fill your label in REVIEW_LOCAL.md, then run `python bench/apply_review.py --dry` and, if it looks right, without --dry.", "", RULE], []
loc = list(pub)
n = 0
for fn, title in SETS:
    gold = json.loads((ROOT / "bench/gold" / fn).read_text(encoding="utf-8"))
    for out in (pub, loc): out += ["", f"# {title}", ""]
    for e in gold:
        b = B.get(e["pr"]); by = {h.id: h for h in b.hunks} if b else {}
        for out in (pub, loc): out += [f"## {e['pr']}", f"_{e.get('title', '')}_", ""]
        for r in e["requirements"]:
            n += 1
            head = f"{n}. **{r['status'].upper()}** ({r.get('confidence', '?')}) R{r['id']}: {r['text'][:170].replace(chr(10), ' ')}"
            note = f" _note: {r['note']}_" if r.get("note") else ""
            ids = ", ".join(f"`{h}`" for h in r.get("hunks", [])[:4])
            pub.append(head + note + (f"\n   hunks: {ids}" if ids else ""))
            lines = [head + note]
            for h in r.get("hunks", [])[:3]:
                if h in by:
                    ex = " | ".join(x.strip() for x in by[h].added[:2])[:150]
                    lines.append(f"   - `{h}`: {ex}")
            lines.append("   your_label: ____   why: ____")
            loc.append("\n".join(lines))
        cr = e.get("creep_hunks") or []
        if cr:
            for out in (pub, loc): out.append("")
            for c in cr:
                cid = c["hunk"] if isinstance(c, dict) else c
                note = f" ({c.get('confidence')}: {c.get('note')})" if isinstance(c, dict) else ""
                pub.append(f"- CREEP label: `{cid}`{note}")
                ex = " | ".join(x.strip() for x in by[cid].added[:2])[:150] if cid in by else ""
                loc.append(f"- CREEP label: `{cid}`{note}\n   {ex}\n   your_label (creep|not creep): ____")
        for out in (pub, loc): out.append("")
(ROOT / "bench/gold/REVIEW.md").write_text("\n".join(pub), encoding="utf-8")
(ROOT / "bench/gold/REVIEW_LOCAL.md").write_text("\n".join(loc), encoding="utf-8")
print(n, "requirements ->", "bench/gold/REVIEW.md and REVIEW_LOCAL.md")
