"""Render docs/RESULTS.md from committed result files only (no hand-typed numbers)."""
import json
from pathlib import Path
R = Path(__file__).resolve().parent / "results"
OUT = Path(__file__).resolve().parents[1] / "docs" / "RESULTS.md"

def wilson(k, n, z=1.96):
    p = k / n; d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return c - h, c + h

def ci(s, k):
    v = s.get(k)
    if not v:
        a, b = str(s.get("fault_catch_rate_not_done", "")).split("/") if "/" in str(s.get("fault_catch_rate_not_done", "")) else (None, None)
        if a is None:
            return "n/a"
        v = wilson(int(a), int(b))
    return f"{v[0]:.2f}-{v[1]:.2f}"

rows = []
o = json.loads((R / "gold_eval.json").read_text(encoding="utf-8"))["summary"]
rows.append(("ours-only (trained models)", o))
for tag, name in [("top5", "hybrid: our top-5 hunks + LLM judge + our verifier"),
                  ("all", "hybrid ablation: judge sees all hunks (no retrieval)"),
                  ("top5_noverify", "hybrid ablation: no verifier"),
                  ("lexical_top5", "hybrid ablation: lexical word-overlap retrieval instead of our CodeBERT retriever")]:
    p = R / f"gold_eval_llm_{tag}.json"
    if p.exists():
        rows.append((name, json.loads(p.read_text(encoding="utf-8"))["summary"]))
for _i, (_n, _s) in enumerate(rows):
    if _s.get('judge_errors'): rows[_i] = (_n + f" **(INVALID: {_s['judge_errors']} judge calls failed)**", _s)

L = ["# Results (generated by bench/make_results_md.py)", "",
     "Gold set: 14 PRs. Labels were drafted by Claude, approved by the owner without changes, then cross-checked by Claude, who changed 5 (docs/GOLD_CHANGES.md). Single annotator; no second labeller.",
     "Faults: all hunks a requirement points at are removed; controls share no hunks with the fault.", "",
     "| variant | done precision | done recall | abstained | faults no longer 'done' | 95% CI | faults -> 'missing' | false alarms | judge errors |",
     "|---|---|---|---|---|---|---|---|---|"]
for n, s in rows:
    L.append(f"| {n} | {s.get('done_precision')} | {s.get('done_recall')} | {s.get('abstained')} | "
             f"{s.get('fault_catch_rate_not_done', s.get('fault_catch_not_done'))} | {ci(s,'fault_catch_not_done_95ci')} | "
             f"{s.get('fault_catch_rate_missing', s.get('fault_catch_missing'))} | "
             f"{s.get('false_alarm_other_reqs')} | {s.get('judge_errors', 'n/a')} |")
L += ["", "Caveats: faults are injected only where the baseline said 'done', so denominators differ per row;",
      "gold base rate of 'done' is 39/42, so precision must be read against 0.85; judge calls were mostly Groq gpt-oss-120b."]
big = []
for tag, name in [("large_top5", "large PRs (36-98 hunks): top-5 + verifier"),
                  ("large_all", "large PRs: judge sees all hunks (prompt is length-capped)"),
                  ("large_top5_noverify", "large PRs: top-5, no verifier"),
                  ("large_lexical_top5", "large PRs: lexical retrieval instead of our CodeBERT retriever")]:
    p = R / f"gold_eval_llm_{tag}.json"
    if p.exists():
        _s = json.loads(p.read_text(encoding="utf-8"))["summary"]
        big.append((name + (f" **(INVALID: {_s['judge_errors']} judge calls failed, HTTP 413/429)**" if _s.get('judge_errors') else ""), _s))
if big:
    L += ["", "### Large PRs (4 PRs, 13 requirements; labels by Claude, NOT human-reviewed; tiny sample)", "",
          "| variant | done precision | done recall | abstained | faults no longer 'done' | 95% CI | faults -> 'missing' | false alarms | judge errors | confusion gold x pred [done,partial,missing,unclear] |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for n, s in big:
        L.append(f"| {n} | {s.get('done_precision')} | {s.get('done_recall')} | {s.get('abstained')} | {s.get('fault_catch_not_done')} | "
                 f"{ci(s,'fault_catch_not_done_95ci')} | {s.get('fault_catch_missing')} | {s.get('false_alarm_other_reqs')} | {s.get('judge_errors', 'n/a')} | "
                 f"{s.get('confusion_gold_x_pred[done,partial,missing,unclear]')} |")

rp = R / "retrieval.json"
if rp.exists():
    _r = json.loads(rp.read_text(encoding="utf-8"))
    L += ["", f"### Retrieval only: is the right hunk in the top k? ({_r['n_requirements']} gold requirements, {_r['n_prs']} PRs; no LLM involved)", "",
          "| retrieval | hit@1 | hit@3 | hit@5 (95% CI) | hit@5 on PRs with 10+ hunks (n=10) |", "|---|---|---|---|---|"]
    for name, v in _r["variants"].items():
        big = v.get("hit@5_big_prs", {})
        L.append(f"| {name} | {v['hit@1']['value']} | {v['hit@3']['value']} | {v['hit@5']['value']} {v['hit@5']['ci']} | {big.get('value', 'n/a')} |")
    _v = next(iter(_r["variants"].values()))
    L += ["", f"Random ranking would reach hit@5 = {_v['hit@5']['random_baseline']} overall (most gold PRs are small) and "
          f"{_v['hit@5_big_prs']['random_baseline']} on the large ones, so only the large-PR column discriminates, and with n=10 a "
          "difference of one or two requirements is noise. No gold PR was in the CodeBERT training set (gold PRs were held out). "
          "Reading: our trained retriever is not better than word-overlap or BM25 on its own; the CodeBERT+lexical fusion is nominally "
          "best (0.97 / 0.80) but the intervals overlap, so that is a hypothesis, not a result. Boosting BM25 / word overlap with identifiers the requirement names verbatim (backticked names, file paths, snake_case/camelCase; fixed weights chosen before looking at the results) raised hit@1 from 0.66 to 0.73 and 0.59 to 0.67 with no loss at hit@5; that is about 5 of 73 requirements and does not help on large PRs, so it is a candidate, not an established gain."]
OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
txt = "\n".join(L)
RM = OUT.parents[1] / "README.md"
if RM.exists():
    r = RM.read_text(encoding="utf-8")
    a, b = r.find("<!-- RESULTS:START -->"), r.find("<!-- RESULTS:END -->")
    if a != -1 and b != -1:
        RM.write_text(r[:a] + "<!-- RESULTS:START -->\n" + txt.split("\n", 2)[2] + "\n" + r[b:], encoding="utf-8")
print(txt)
